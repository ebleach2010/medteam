const BUB = {
  stable: ['Still here... still patient. Mostly.', 'Any update, doc?', '*waits dramatically*'],
  worse: ['I feel... worse. Distinctly worse.', 'This is trending badly...', 'Doc? DOC?'],
  better: ['Oh wow. I feel human again.', 'You people are wizards.', 'MUCH better.'],
  critical: ['*fading fast*', '*can barely respond*', 'help... please...'],
};

function C(tier, id, name, complaint, hx, dx, meds, dispo, o = {}) {
  const t = TIER[tier];
  const fm = FAIL[o.fail ?? 'shock'];
  const pace = o.pace ?? 1;
  const timeline = o.timeline !== undefined ? o.timeline
    : t.times ? [
      { t: t.times[0] * pace, vitals: fm[0], bubble: 'worse' },
      { t: t.times[1] * pace, event: 'critical' },
      { t: t.times[2] * pace, event: 'death', cause: o.cause ?? fm[1] },
    ] : [];
  return {
    id, name, tier,
    ambulatory: o.amb ?? true,
    complaint: Array.isArray(complaint) ? complaint : [complaint],
    history: hx,
    bubbles: { ...BUB, ...(o.bub ?? {}) },
    vitals: { ...NORM, ...(o.v ?? {}) },
    timeline,
    labs: o.labs === null ? null : { CBC: 'normal', BMP: 'normal', ...(o.labs ?? {}) },
    imaging: o.img ?? null,
    ekg: o.ekg ?? null,
    neuro: o.neuro ?? null,
    physical: o.phys ?? null,
    dxOptions: dx, correctDx: 0,
    treatment: { meds, dispo },
    contra: o.contra ?? [],
    labsRequiredForMeds: o.labsFirst ?? undefined,
    tpaNeedsCT: o.tpaCT ?? undefined,
    agitateOnTreat: o.agitTx ?? undefined,
    agitationRisk: o.agit ?? t.agit,
    patienceMin: o.patience ?? t.patience,
    score: o.score ?? t.score,
    rescueChance: o.rescue ?? t.rescue,
  };
}
